def render_report(
    findings: list[Finding], *, figures_rel: str, observations: list[Finding] | None = None
) -> str:
    observations = observations or []
    lines = [
        "# Data report - Austin_TX_US_2020.csv",
        "",
        "> Generated by `python -m energymind.eda`. All numbers below are computed "
        "from the data, not hard-coded.",
        "",
        "The input is a synthetic single-city panel: **13 smart-metered households, "
        "30-minute interval, 1 Jan - 30 Dec 2020, 104 columns**. It carries "
        "Tunisian-grid-compatible electrical parameters (230 V, 50 Hz) on an Austin "
        "calendar and climate; we state this explicitly in the paper.",
        "",
        "The findings shape the whole pipeline (drop derived columns, mask the "
        "provided labels, inject consistently, use cross-household coherence).",
        "",
        f"![overview]({figures_rel}/dataset_overview.png)",
        "",
        "| # | Finding | Consequence |",
        "| --- | --- | --- |",
    ]
    for f in [*findings, *observations]:
        lines.append(f"| {f.code} | {f.title} | {f.consequence} |")

    lines.append("")
    for f in [*findings, *observations]:
        lines.append(f"## {f.code} - {f.title}")
        lines.append("")
        lines.append("| Metric | Value |")
        lines.append("| --- | --- |")
        for label, value in f.metrics:
            lines.append(f"| {label} | {value} |")
        lines.append("")
        lines.append(f"**Consequence.** {f.consequence}")
        figs = [f.figure] if isinstance(f.figure, str) else (f.figure or [])
        for fig in figs:
            name = fig.removesuffix(".png")
            lines.append("")
            lines.append(f"![{f.code}]({figures_rel}/{fig})")
            if name in CAPTIONS:
                lines.append("")
                lines.append(f"*{CAPTIONS[name]}*")
        lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Entry point
# --------------------------------------------------------------------------- #


def prepare(settings: Settings):
    """Load everything the figures need: engineered baseline, raw subset, labels."""
    df = clean.load_baseline(settings)
    raw = load_raw_subset(settings)
    labels = pd.read_parquet(io.resolve(settings.data.paths.clean_dir) / "provided_labels.parquet")
    splits = eda_plots.split_bounds(settings)
    fx = eda_features.engineer_features(df, splits["train"][1])
    return df, fx, raw, labels, splits


def run(settings: Settings | None = None) -> list[Finding]:
    settings = settings or load_settings()
    df, fx, raw, labels, splits = prepare(settings)
    findings = compute_findings(df, raw)
    observations = compute_observations(fx, splits)

    figures_dir = io.resolve("results/figures")
    eda_plots.generate_all(fx, raw, labels, settings, figures_dir)

    report = render_report(findings, figures_rel="../results/figures", observations=observations)
    report_path = io.resolve("docs/data_report.md")
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(report, encoding="utf-8")
    return [*findings, *observations]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Step 3: EDA figures + data report.")
    parser.add_argument("--configs-dir", default=None)
    args = parser.parse_args(argv)

    matplotlib.use("Agg", force=True)
    settings = load_settings(args.configs_dir) if args.configs_dir else load_settings()
    findings = run(settings)

    print("Step 3 complete")
    for f in findings:
        print(f"  {f.code}: {f.title}")
        for label, value in f.metrics:
            print(f"       {label}: {value}")
    print(f"  wrote figures -> {io.resolve('results/figures')}")
    print(f"  wrote report  -> {io.resolve('docs/data_report.md')}")
    return 0


