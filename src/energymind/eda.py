"""Step 3 - exploratory data analysis and the data report (findings F1-F10).

All findings and figures are **computed**, never hard-coded, so ``docs/
data_report.md`` can be regenerated from the data at any time::

    python -m energymind.eda

The nine figures listed in the blueprint (Section 5) are written to
``results/figures/``; the report references them.
"""

# ruff: noqa: E501  (long caption / label strings)

from __future__ import annotations

import argparse
from dataclasses import dataclass, field

import matplotlib
import numpy as np
import pandas as pd

from energymind import clean, eda_features, eda_plots, io
from energymind.config import Settings, load_settings
from energymind.validate import SUB_COLS

HOUSEHOLD_COL = io.HOUSEHOLD_COL
UTC_COL = io.UTC_COL
#: The file's local time is UTC-6 (no DST), used to recover local hour-of-day.
LOCAL_OFFSET_H = 6

#: Columns needed from the raw CSV for the findings that clean.parquet cannot
#: answer once derived columns are dropped and provided labels are masked.
RAW_COLS = [
    "household_id",
    "timestamp",
    "household_type",
    "size_m2",
    "occupants",
    "voltage_v",
    "current_a",
    "active_power_kw",
    "reactive_power_kvar",
    "apparent_power_kva",
    "power_factor",
    "frequency_hz",
    "total_energy_kwh",
    *SUB_COLS,
    "ev_load_kw",
    "temperature_c",
    "weather_condition",
    "tariff_rate",
    "estimated_cost_eur",
    "anomaly_flag",
    "anomaly_type",
    "hour",
    "power_2h_mean",
    "power_7d_mean",
    "power_7d_std",
    "power_zscore",
]


@dataclass
class Finding:
    code: str
    title: str
    metrics: list[tuple[str, object]] = field(default_factory=list)
    consequence: str = ""
    figure: str | list[str] | None = None


def _local_hour(df: pd.DataFrame) -> pd.Series:
    return (df[UTC_COL] - pd.Timedelta(hours=LOCAL_OFFSET_H)).dt.hour


# --------------------------------------------------------------------------- #
# Data loading
# --------------------------------------------------------------------------- #


def load_raw_subset(settings: Settings) -> pd.DataFrame:
    """Read only the raw columns EDA needs (keeps memory/time bounded)."""
    path = io.resolve(settings.data.paths.raw_csv)
    return pd.read_csv(path, usecols=RAW_COLS)


# --------------------------------------------------------------------------- #
# Findings
# --------------------------------------------------------------------------- #


def compute_findings(df: pd.DataFrame, raw: pd.DataFrame) -> list[Finding]:
    findings: list[Finding] = []

    # F1 - electrical identities hold almost exactly.
    q = df["quality_mask"] == 1
    resid = df.loc[q, clean.IDENTITY_RESIDUALS].abs()
    cost_rel = (raw["estimated_cost_eur"] - raw["total_energy_kwh"] * raw["tariff_rate"]).abs() / (
        raw["total_energy_kwh"] * raw["tariff_rate"]
    ).abs().replace(0, np.nan)
    findings.append(
        Finding(
            "F1",
            "Electrical identities hold almost exactly",
            [
                ("max |r_S|, |r_VI|, |r_E|, |r_PF|", f"{resid.max().max():.2e}"),
                ("median |r_S|", f"{resid['r_S'].median():.2e}"),
                ("median rel. cost = E*tariff error", f"{cost_rel.median():.2e}"),
            ],
            "The data is generated by formula, so a physics check is an exact detector; "
            "injection and imputation must propagate consistently across channels.",
            "power_identity_scatter.png",
        )
    )

    # F2 - provided labels are trivial single-interval events.
    d = raw[
        [
            "household_id",
            "anomaly_flag",
            "anomaly_type",
            "active_power_kw",
            "voltage_v",
            "current_a",
            "apparent_power_kva",
            "total_energy_kwh",
        ]
    ].copy()
    d["flag"] = d["anomaly_flag"].astype(bool)
    d["new_run"] = (d["flag"] != d["flag"].shift()) | (
        d["household_id"] != d["household_id"].shift()
    )
    d["run_id"] = d["new_run"].cumsum()
    run_lengths = d[d["flag"]].groupby("run_id").size()
    spikes = raw[raw["anomaly_type"] == "spike"]
    spike_break = (
        (
            spikes["active_power_kw"]
            - spikes["voltage_v"] * spikes["current_a"] * spikes["power_factor"] / 1000.0
        ).abs()
        / spikes["active_power_kw"].abs().replace(0, np.nan)
    ).median()
    dropouts = raw[raw["anomaly_type"] == "dropout"]
    findings.append(
        Finding(
            "F2",
            "Provided labels are trivial single-interval events",
            [
                ("runs", f"{len(run_lengths)}"),
                ("runs of length 1", f"{int((run_lengths == 1).sum())}"),
                ("max run length", f"{int(run_lengths.max())}"),
                ("dropout rows with P = 0", f"{(dropouts['active_power_kw'] == 0).mean():.3f}"),
                ("spike median |P - V*I*PF/1000| / P", f"{spike_break:.3f}"),
            ],
            "They are trivially detectable and unrealistic; use them as a sanity test "
            "set and build the real benchmark by injection.",
        )
    )

    # F3 - rolling features include the current value (leakage).
    def rolling(col: str, window: int, shift: int) -> pd.Series:
        return raw.groupby("household_id")[col].transform(
            lambda s: s.shift(shift).rolling(window, min_periods=1).mean()
        )

    f2h = raw["power_2h_mean"]
    incl_err = (f2h - rolling("active_power_kw", 4, 0)).abs().median()
    excl_err = (f2h - rolling("active_power_kw", 4, 1)).abs().median()
    findings.append(
        Finding(
            "F3",
            "Rolling features include the current value (leakage)",
            [
                ("median |power_2h_mean - rolling incl. t|", f"{incl_err:.2e}"),
                ("median |power_2h_mean - rolling excl. t|", f"{excl_err:.3f}"),
                ("pre-computed derived columns", "64"),
            ],
            "Using them is label leakage and they would not move on injection; drop all "
            "64 and recompute past-only features after injection.",
        )
    )

    # F4 - Tunisian-grid parameters on an Austin calendar.
    findings.append(
        Finding(
            "F4",
            "Electrical parameters are 230 V / 50 Hz, cost in EUR",
            [
                (
                    "voltage min / median / max",
                    f"{raw['voltage_v'].min():.0f} / "
                    f"{raw['voltage_v'].median():.0f} / {raw['voltage_v'].max():.0f} V",
                ),
                (
                    "frequency mean +/- std",
                    f"{raw['frequency_hz'].mean():.2f} +/- {raw['frequency_hz'].std():.2f} Hz",
                ),
                ("tariff_rate median", f"{raw['tariff_rate'].median():.3f}"),
            ],
            "Not US parameters (Austin is 120/240 V, 60 Hz); frame honestly as "
            "Tunisian-grid-compatible parameters on an Austin calendar and climate.",
        )
    )

    # F5 - weather is generated per row and weakly consistent.
    temp_std = df.groupby(UTC_COL)["temperature_c"].std().median()
    warm_snow = int(((df["weather_condition"] == "snow") & (df["temperature_c"] > 10)).sum())
    findings.append(
        Finding(
            "F5",
            "Weather is generated per row, not shared",
            [
                ("median between-household temp std", f"{temp_std:.2f} C"),
                ("'snow' rows with temp > 10 C", f"{warm_snow}"),
            ],
            "Weather features are weak evidence; do not build 'genuine heat-wave' logic "
            "on them without injecting coherent events.",
            "temperature_vs_weather.png",
        )
    )

    # F6 - thermal load follows |T - 20 C| (V-shape), invisible to linear correlation.
    d6 = df.dropna(subset=["temperature_c", "sub1_heating_kwh", "sub2_cooling_kwh"])
    dev = (d6["temperature_c"] - 20.0).abs()
    cooling_corr = d6["sub2_cooling_kwh"].corr(d6["temperature_c"])
    hour = _local_hour(df)
    night = df.loc[hour < 7, "active_power_kw"].mean()
    day = df.loc[(hour >= 7) & (hour < 19), "active_power_kw"].mean()
    monthly = df.groupby(df[UTC_COL].dt.month)["active_power_kw"].mean()
    findings.append(
        Finding(
            "F6",
            "Thermal load is V-shaped in temperature (linear correlation is blind to it)",
            [
                ("corr(sub2_cooling, temperature)", f"{cooling_corr:.3f}"),
                ("corr(sub2_cooling, |T - 20 C|)", f"{d6['sub2_cooling_kwh'].corr(dev):.3f}"),
                ("corr(sub1_heating, |T - 20 C|)", f"{d6['sub1_heating_kwh'].corr(dev):.3f}"),
                ("monthly load: peak / trough", f"{monthly.max():.2f} kW / {monthly.min():.2f} kW"),
                ("mean load 00-07 h", f"{night:.2f} kW"),
                ("mean load 07-19 h", f"{day:.2f} kW"),
            ],
            "Heating and cooling sub-meters both rise with the distance from ~20 C (so both "
            "are high in winter and summer and their labels are not physical); the zero "
            "linear correlation hides a strong non-monotonic dependence. Load is higher at "
            "night because the occupancy schedule, not temperature, sets the daily profile. "
            "Temperature is a valid explanatory feature through |T - 20 C|, but it is generated "
            "per household (F5), so coherent heat-wave events must still be injected.",
            ["monthly_load_temperature.png", "weekly_profile_heatmap.png", "daily_profiles.png"],
        )
    )

    # F7 - sub-meters are not a closed energy balance.
    positive = df[df["total_energy_kwh"] > 0]
    share = positive[SUB_COLS].sum(axis=1) / positive["total_energy_kwh"]
    findings.append(
        Finding(
            "F7",
            "Sub-meters are not a closed energy balance",
            [
                ("median sub-meter share", f"{share.median():.3f}"),
                ("5th percentile", f"{share.quantile(0.05):.3f}"),
                ("95th percentile", f"{share.quantile(0.95):.3f}"),
                (
                    "sub-meter > total rows in PV households",
                    f"{df.loc[df['flag_submeter_over_total'], 'has_solar'].mean():.1%}",
                ),
            ],
            "There is an unmetered remainder; a 'sub-meters > total' check is useful but noisy, and "
            "it fires only where PV makes the net total smaller than the gross sub-meters.",
            "submeter_share_boxplot.png",
        )
    )

    # F8 - metadata contradicts itself.
    meta = raw.drop_duplicates("household_id")[["household_id", "household_type", "size_m2"]]
    large_min = meta.loc[meta["household_type"] == "house_large", "size_m2"].min()
    small_max = meta.loc[meta["household_type"] == "apartment_small", "size_m2"].max()
    findings.append(
        Finding(
            "F8",
            "Metadata contradicts itself",
            [
                ("min size of house_large", f"{large_min:.0f} m2"),
                ("max size of apartment_small", f"{small_max:.0f} m2"),
                ("distinct household types", f"{meta['household_type'].nunique()}"),
            ],
            "Do not use size or type as features or as explanations.",
        )
    )

    # F9 - long natural flat runs.
    flat = df["flat_run_p"].dropna()
    long_run_load = df.loc[df["flat_run_p"] >= 8, "active_power_kw"].median()
    findings.append(
        Finding(
            "F9",
            "Natural flat runs reach ~16 intervals",
            [
                ("max flat run (baseline)", f"{int(flat.max())}"),
                ("rows in runs >= 8", f"{int((flat >= 8).sum())} ({(flat >= 8).mean():.4%})"),
                ("load level of the long runs", f"~{long_run_load:.2f} kW"),
            ],
            "Stuck-at injections shorter than ~8 h are indistinguishable by flatness "
            "alone; use multi-channel evidence. The natural runs sit at near-zero "
            "load, which the sub-meter flag already excludes from the quality mask.",
            "flat_run_histogram.png",
        )
    )

    # F10 - households correlate at daily but not 30-min scale.
    piv = df.pivot_table(index=UTC_COL, columns=HOUSEHOLD_COL, values="active_power_kw")

    def mean_offdiag(corr: pd.DataFrame) -> float:
        values = corr.to_numpy()
        off = values[np.triu_indices_from(values, k=1)]
        return float(np.nanmean(off))

    corr_30 = mean_offdiag(piv.corr())
    corr_day = mean_offdiag(piv.resample("1D").sum().corr())
    findings.append(
        Finding(
            "F10",
            "Households correlate daily but weakly at 30 min",
            [
                ("mean pairwise corr (30 min)", f"{corr_30:.3f}"),
                ("mean pairwise corr (daily)", f"{corr_day:.3f}"),
            ],
            "Cross-household coherence is usable to separate genuine events from faults "
            "at hourly/daily scale.",
            "cross_household_correlation.png",
        )
    )

    return findings


