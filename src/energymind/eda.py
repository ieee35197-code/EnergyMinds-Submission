def compute_observations(fx: pd.DataFrame, splits: dict) -> list[Finding]:
    """Observations O1-O3 that the figures reveal beyond F1-F10."""
    obs: list[Finding] = []

    # O1 - the daily profile is a two-level occupancy schedule.
    occ = fx.groupby("slot")["occupancy_probability"].mean()
    away = fx["slot"].between(18, 35)  # 09:00-17:30
    r = fx["active_power_kw"].corr(fx["occupancy_probability"])
    wk = fx["dow"] >= 5
    up = (
        fx[wk].groupby("household_type")["active_power_kw"].mean()
        / fx[~wk].groupby("household_type")["active_power_kw"].mean()
        - 1.0
    )
    obs.append(
        Finding(
            "O1",
            "The daily profile is a two-level occupancy schedule",
            [
                (
                    "occupancy probability, 18-09 h / 09-18 h",
                    f"{occ[~occ.index.isin(range(18, 36))].mean():.2f} / {occ[range(18, 36)].mean():.2f}",
                ),
                ("corr(P, occupancy_probability)", f"{r:.2f}"),
                ("weekend vs weekday load", f"{up.min():+.1%} to {up.max():+.1%}"),
                (
                    "commercial_small day/night ratio",
                    f"{fx[fx['household_type'] == 'commercial_small'].loc[away, 'active_power_kw'].mean() / fx[(fx['household_type'] == 'commercial_small') & ~away]['active_power_kw'].mean():.2f}",
                ),
            ],
            "Load steps down at 09:00 and up at 18:00 for residential types; the hour-of-week "
            "baseline therefore reduces to a two-level schedule plus a small weekend uplift.",
            ["daily_profiles.png", "weekly_profile_heatmap.png"],
        )
    )

    # O2 - DER signatures.
    solar = fx[fx["has_solar"].eq(1)]
    mid = solar[solar["hour_local"].between(10, 14)].dropna(subset=["cloud_cover_pct"])
    cf = mid["solar_generation_kw"] / mid["solar_capacity_kwp"]
    ev = fx[fx["has_ev"].eq(1)]
    window = ev["hour_local"].ge(18) | ev["hour_local"].lt(8)
    obs.append(
        Finding(
            "O2",
            "DER channels have clean, learnable signatures",
            [
                (
                    "corr(PV / capacity, cloud cover), 10-14 h",
                    f"{cf.corr(mid['cloud_cover_pct']):.2f}",
                ),
                (
                    "PV output at night",
                    f"{solar.loc[solar['hour_local'].lt(5) | solar['hour_local'].gt(20), 'solar_generation_kw'].max():.1f} kW (max)",
                ),
                (
                    "EV charging probability, 18-08 h / 08-18 h",
                    f"{(ev.loc[window, 'ev_load_kw'] > 0).mean():.2f} / {(ev.loc[~window, 'ev_load_kw'] > 0).mean():.4f}",
                ),
                (
                    "EV on-power median (range)",
                    f"{ev.loc[ev['ev_load_kw'] > 0, 'ev_load_kw'].median():.1f} kW ({ev.loc[ev['ev_load_kw'] > 0, 'ev_load_kw'].min():.1f}-{ev['ev_load_kw'].max():.1f})",
                ),
            ],
            "PV is zero at night and tied to cloud cover; EV charging is confined to 18-08 h and "
            "dominates the household's power (bimodal load). Detectors need household-specific "
            "or DER-aware baselines, and PV can legitimately push net load far below the "
            "household's peers at midday.",
            ["der_profiles.png", "power_distribution_log.png"],
        )
    )

    # O3 - a baseline fitted on Jan-Aug drifts in the validation/test months.
    zs, kwh = {}, {}
    daily = fx.groupby([io.HOUSEHOLD_COL, "date_local"])["total_energy_kwh"].sum()
    for name, (a, b) in splits.items():
        z = fx.loc[(fx["ts_local"] >= a) & (fx["ts_local"] < b), "p_resid_z"].dropna()
        zs[name] = float(z.median())
        d = daily[(daily.index.get_level_values(1) >= a) & (daily.index.get_level_values(1) < b)]
        kwh[name] = float(d.median())
    obs.append(
        Finding(
            "O3",
            "A baseline fitted on the training months drifts in validation and test",
            [
                (
                    "median daily energy, train / val / test",
                    " / ".join(f"{kwh[k]:.0f} kWh" for k in splits),
                ),
                (
                    "median residual z, train / val / test",
                    " / ".join(f"{zs[k]:+.2f}" for k in splits),
                ),
            ],
            "Seasonality (F6) shifts the level between splits, so a fixed hour-of-week baseline "
            "produces biased residuals out of sample. Step 6 should add |T - 20 C| or a "
            "trailing seasonal level, and thresholds must be fixed on validation only.",
            ["temporal_splits.png", "engineered_features.png"],
        )
    )
    return obs


